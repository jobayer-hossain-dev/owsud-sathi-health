import 'dart:io';
import 'package:path_provider/path_provider.dart';
import 'package:share_plus/share_plus.dart';

class PdfReportService {
  static Future<String> generateHealthReport({
    required String userName,
    required String userPhone,
    required List bpLogs,
    required List sugarLogs,
    required List weightLogs,
    required List pulseLogs,
    required List medicines,
  }) async {
    final now = DateTime.now();
    final dateStr = '${now.year}-${now.month.toString().padLeft(2, '0')}-${now.day.toString().padLeft(2, '0')}';

    final StringBuffer buffer = StringBuffer();
    buffer.writeln('====================================================');
    buffer.writeln('          OSHUDHSATHI - HEALTH REPORT               ');
    buffer.writeln('====================================================');
    buffer.writeln('Report Date: $dateStr');
    buffer.writeln('Patient Name: $userName');
    buffer.writeln('Phone: $userPhone');
    buffer.writeln('----------------------------------------------------');
    buffer.writeln();

    buffer.writeln('1. CURRENT REGULAR MEDICATIONS');
    buffer.writeln('----------------------------------------------------');
    if (medicines.isEmpty) {
      buffer.writeln('No active medicines logged.');
    } else {
      for (final m in medicines) {
        buffer.writeln('- ${m.displayName} | Frequency: ${m.frequency} | Times: ${m.times.join(', ')}');
      }
    }
    buffer.writeln();

    buffer.writeln('2. BLOOD PRESSURE LOGS (LAST 30 DAYS)');
    buffer.writeln('----------------------------------------------------');
    if (bpLogs.isEmpty) {
      buffer.writeln('No blood pressure logs recorded.');
    } else {
      for (final bp in bpLogs) {
        final val = bp.value2 != null ? '${bp.value1.toInt()}/${bp.value2.toInt()}' : '${bp.value1}';
        buffer.writeln('- Date: ${bp.recordedAt.toString().split('T')[0]} | Value: $val mmHg');
      }
    }
    buffer.writeln();

    buffer.writeln('3. BLOOD SUGAR LOGS (LAST 30 DAYS)');
    buffer.writeln('----------------------------------------------------');
    if (sugarLogs.isEmpty) {
      buffer.writeln('No blood sugar logs recorded.');
    } else {
      for (final s in sugarLogs) {
        buffer.writeln('- Date: ${s.recordedAt.toString().split('T')[0]} | Value: ${s.value1} mmol/L | Context: ${s.mealContext ?? 'N/A'}');
      }
    }
    buffer.writeln();

    buffer.writeln('4. WEIGHT & PULSE SUMMARY');
    buffer.writeln('----------------------------------------------------');
    if (weightLogs.isNotEmpty) {
      buffer.writeln('Latest Weight: ${weightLogs.last.value1} kg');
    }
    if (pulseLogs.isNotEmpty) {
      buffer.writeln('Latest Pulse (HBR): ${pulseLogs.last.value1} bpm');
    }
    buffer.writeln();

    buffer.writeln('====================================================');
    buffer.writeln(' Generated by OshudhSathi App (Offline Health System)');
    buffer.writeln('====================================================');

    String targetPath = '';

    try {
      Directory? downloadsDir;
      try {
        downloadsDir = await getApplicationDocumentsDirectory();
      } catch (_) {
        downloadsDir = await getTemporaryDirectory();
      }

      final String fileName = 'OshudhSathi_Health_Report_$dateStr.txt';
      final File file = File('${downloadsDir.path}/$fileName');
      await file.writeAsString(buffer.toString());
      targetPath = file.path;
    } catch (e) {
      final Directory tempDir = await getTemporaryDirectory();
      final File file = File('${tempDir.path}/OshudhSathi_Health_Report_$dateStr.txt');
      await file.writeAsString(buffer.toString());
      targetPath = file.path;
    }

    return targetPath;
  }

  static Future<void> shareReportFile(String filePath) async {
    try {
      final XFile file = XFile(filePath);
      await Share.shareXFiles([file], text: '📄 ওষুধসাথী হেলথ রিপোর্ট');
    } catch (_) {}
  }

  static Future<List<File>> getSavedReports() async {
    try {
      Directory? downloadsDir;
      try {
        downloadsDir = await getApplicationDocumentsDirectory();
      } catch (_) {
        downloadsDir = await getTemporaryDirectory();
      }
      final files = downloadsDir.listSync();
      final reportFiles = files
          .whereType<File>()
          .where((f) => f.path.contains('OshudhSathi_Health_Report_'))
          .toList();
      reportFiles.sort((a, b) => b.lastModifiedSync().compareTo(a.lastModifiedSync()));
      return reportFiles;
    } catch (_) {
      return [];
    }
  }
}
